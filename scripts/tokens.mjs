import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const source = JSON.parse(readFileSync(new URL('../src/tokens/foundations.tokens.json', import.meta.url), 'utf8'));
export function cssValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'color':
      assert.equal(v.colorSpace, 'srgb');
      assert.equal(v.alpha, 1);
      assert.equal(v.components.length, 3);
      assert(v.components.every(n => Number.isFinite(n) && n >= 0 && n <= 1));
      return '#' + v.components.map(n => Math.round(n * 255).toString(16).padStart(2, '0')).join('');
    case 'dimension':
    case 'duration':
      assert(Number.isFinite(v.value));
      assert((token.$type === 'dimension' ? ['px', 'rem'] : ['ms', 's']).includes(v.unit));
      return `${v.value}${v.unit}`;
    case 'number': assert(Number.isFinite(v)); return String(v);
    case 'fontFamily':
      assert(Array.isArray(v) && v.every(x => typeof x === 'string' && x.length > 0));
      return v.map(x => /\s/.test(x) ? JSON.stringify(x) : x).join(', ');
    case 'cubicBezier':
      assert(Array.isArray(v) && v.length === 4 && v.every(Number.isFinite));
      assert(v[0] >= 0 && v[0] <= 1 && v[2] >= 0 && v[2] <= 1);
      return `cubic-bezier(${v.join(', ')})`;
    default: throw new Error(`Tipo não suportado: ${token.$type}`);
  }
}
export function declarations(group) {
  const values = {};
  for (const [name, token] of Object.entries(group)) {
    if (name.startsWith('$')) continue;
    assert(token.$description && typeof token.$deprecated === 'boolean', `Metadados: ${name}`);
    values[`--${name}`] = cssValue(token);
  }
  for (const [name, entry] of Object.entries(group.$extensions['org.refy.css'])) {
    assert(/^--[\w-]+$/.test(name) && typeof entry.value === 'string' && entry.description);
    values[name] = entry.value;
  }
  return values;
}
export function themeValues(mode) {
  assert(['light', 'dark', 'editorial'].includes(mode), `Modo inválido: ${mode}`);
  return { ...declarations(source.base), ...declarations(source[mode]) };
}
export function generateCSS() {
  const block = (selector, values) => `${selector} {\n${Object.entries(values).sort(([a], [b]) => a.localeCompare(b, 'en')).map(([key, value]) => `  ${key}: ${value};`).join('\n')}\n}\n`;
  // Repeat inherited aliases at each scope so custom properties resolve to that scope's palette.
  return '/* Generated by npm run tokens:build. Edit foundations.tokens.json. */\n' +
    block(':root, :where([data-refy-scope]), [data-theme="light"]', { ...themeValues('light'), 'color-scheme': 'light' }) +
    ['dark', 'editorial'].map(mode => block(`[data-theme="${mode}"]`, { ...themeValues(mode), 'color-scheme': mode === 'dark' ? 'dark' : 'light' })).join('\n');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/tokens/tokens.css', import.meta.url), generateCSS());
  console.log('OK: tokens.css gerado a partir da fonte estruturada.');
}
